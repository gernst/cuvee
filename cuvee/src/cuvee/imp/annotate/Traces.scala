package cuvee.imp.annotate

import cuvee.util.Counter
import cuvee.imp._
import cuvee.pure._
import cuvee.imp.traces._
import cuvee.State
import cuvee.smtlib.Cmd
import cuvee.Cuvee
import cuvee.util.Run
import cuvee.util.Name
import scala.collection.immutable
import cuvee.smtlib.DeclareSort
import cuvee.smtlib.DeclareFun

object Current extends Sugar.unary(Fun.current)
object Earlier extends Sugar.binary(Fun.earlier)
object Butlast extends Sugar.unary(Fun.butlast)

object Counter extends Sugar.unary(Fun.counter)

object Traces extends Annotate(ExecNoLoops) {
  override def preamble(state: State) = {
    val (cmds, _) = cuvee.boogie.parse("cuvee/src/cuvee/imp/traces.bpl")
    state.add(cmds) // make the commands visible in this stage's state!
    cmds
  }

  def auxiliary(paths: Paths, xs: List[Var]): Paths = {
    import paths._
    val running_ = running map { _ auxiliary xs }
    Paths(running_, breaked, returned, asserted)
  }

  def while_(
      state: State,
      paths: Paths,
      test: Expr,
      body: Prog,
      term: Expr,
      inv: Expr,
      sum: Expr,
      frames: List[Frame]
  ): (List[Cmd], Paths, Prog) = {

    val mod = body.mod
    val read = body.read

    val vars = test.free ++ mod ++ read
    val xs = vars.toList

    val (cmds_, before, after, body_) =
      iter(state, paths, xs, test, body, term, inv, sum, frames)

    // prepare variables:
    // #k <- counter(#n)
    // ws are all regular modified variables
    // zs are all nondet variables

    // Note: Simplify will keep dependencies if they start with # even if these variables do not occur in the result expression/update.
    //       Make sure to adapt that code whenever names change here.
    val k = Expr.fresh("#k", Sort.int)
    val n = Expr.fresh("#n", Sort.int)

    val ws = mod.toList

    after.running map println

    val zs =
      for (path <- after.running; y <- path.fresh)
        yield y

    val tr =
      for ((x, Var(Name(name, index), typ)) <- Expr.fresh(k :: ws))
        yield (x, Var(Name("@" + name, index), Sort.trace(typ)))

    val nd =
      for ((x, Var(Name(name, index), typ)) <- Expr.fresh(zs))
        yield (x, Var(Name("?" + name, index), Sort.trace(typ)))

    val su = tr ++ nd

    val inv_counter = List(
      Eq(su(k), Counter(n)),
      invariant(k, su, mod ++ zs, after.running)
    )

    val inv_traces =
      for (x <- ws)
        yield Eq(su(x), trace(x, k, su, mod ++ zs, after.running))

    val inv_current =
      for (x <- ws)
        yield Eq(x, Current(su(x)))

    val fresh = n :: tr(k) :: (ws map tr) ::: (zs map nd)

    val cond_ = And(inv_counter ++ inv_traces ++ inv_current)
    val inv_ = Exists(fresh, cond_) note "free"

    val prog_ = While(test, body_, term, inv_, sum, frames)
    val paths_ = exec.spec(auxiliary(paths, fresh), ws, cond_, cond_ && !test)

    (cmds_, paths_, prog_)
  }

  def invariant(k: Var, su: Map[Var, Expr], vars: Set[Var], running: List[Path]) = {
    val conds =
      for (path <- running) // XXX: strip notes gets rid of the "free" annotation of inner invariants
        yield And(path.constraints map (_.stripNotes))

    val cond = Or(conds)
    val ys = cond.free & vars

    val formals =
      for (y <- k :: ys.toList)
        yield LetEq(y, Butlast(su(y)))

    // UH OH. For inner loops, we discard the invariants,
    //        including those generated by trace annotations.

    Invariant(formals, cond)
  }

  def trace(x: Var, k: Var, su: Map[Var, Expr], vars: Set[Var], running: List[Path]) = {
    val ys =
      for (
        path <- running;
        rhs = path lookup x;
        y <- ((path.constraints.free ++ rhs.free) - x) & vars
      )
        yield y

    val formals =
      for (y <- k :: ys.distinct)
        yield LetEq(y, Butlast(su(y)))

    val updates =
      for (path <- running) yield {
        val constraints = path.constraints map (_.stripNotes)
        val rhs = path lookup x
        Update(And(constraints), rhs)
      }

    Trace(init = Old(x), formals, acc = x, updates)
  }
}
